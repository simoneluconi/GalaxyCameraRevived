#!/bin/bash
# Pin every LineageOS/* project of the current repo checkout to the last commit of its branch
# before a cutoff date, and write the result as a local manifest of <extend-project revision=...>.
#
# LineageOS-UL 21 merged LineageOS lineage-21.0 for the last time on 2025-04-04. Its forks never
# moved after that, while LineageOS kept changing APIs (e.g. IUserSwitchObserver in Jan 2026), so the
# LineageOS side must be frozen at the same point in time.
#
# Usage: pin-snapshot.sh <android-root> <cutoff "YYYY-MM-DD HH:MM"> <output-manifest.xml>
set -euo pipefail

root=$1
cutoff=$2
out=$3
cd "$root"

repo manifest -r -o /tmp/pin-manifest.xml 2>/dev/null
python3 - > /tmp/pin-projects.txt <<'EOF'
import re
xml = open('/tmp/pin-manifest.xml').read()
for m in re.finditer(r'<project ([^>]*)/?>', xml):
    attrs = dict(re.findall(r'(\w[\w-]*)="([^"]*)"', m.group(1)))
    if attrs['name'].startswith('LineageOS/'):
        branch = attrs.get('upstream', 'refs/heads/lineage-21.0').replace('refs/heads/', '')
        print(attrs['name'], attrs.get('path', attrs['name']), branch)
EOF

pin_one() {
    local name=$1 path=$2 branch=$3 cutoff=$4
    local url="https://github.com/$name"
    local sha
    # Fetch enough history to cover the cutoff; fall back to the tip if it is already older.
    if git -C "$path" fetch -q --shallow-since="2024-06-01" "$url" "refs/heads/$branch" 2>/dev/null; then
        # --first-parent: follow the branch's own history; merged AOSP side branches keep their
        # original (older) dates and would otherwise be picked instead of the branch state.
        sha=$(git -C "$path" rev-list -1 --first-parent --before="$cutoff" FETCH_HEAD 2>/dev/null || true)
    fi
    if [ -z "${sha:-}" ]; then
        git -C "$path" fetch -q --depth=1 "$url" "refs/heads/$branch" 2>/dev/null || { echo "FAIL $name"; return; }
        if [ "$(git -C "$path" log -1 --format=%ct FETCH_HEAD)" -le "$(date -d "$cutoff" +%s)" ]; then
            sha=$(git -C "$path" rev-parse FETCH_HEAD)
        else
            echo "FAIL $name (no commit before cutoff in fetched history)"; return
        fi
    fi
    echo "PIN $name $sha"
}
export -f pin_one

xargs -P 8 -L 1 bash -c 'pin_one "$0" "$1" "$2" "'"$cutoff"'"' < /tmp/pin-projects.txt > /tmp/pin-results.txt

grep '^FAIL' /tmp/pin-results.txt || true
{
    echo '<?xml version="1.0" encoding="UTF-8"?>'
    echo "<!-- LineageOS projects frozen at $cutoff to match the last LineageOS-UL 21 merge."
    echo "     Generated by tools/pin-snapshot.sh. -->"
    echo '<manifest>'
    grep '^PIN' /tmp/pin-results.txt | sort -k2 | while read -r _ name sha; do
        echo "  <extend-project name=\"$name\" revision=\"$sha\" />"
    done
    echo '</manifest>'
} > "$out"
echo "pinned $(grep -c '^PIN' /tmp/pin-results.txt) of $(wc -l < /tmp/pin-projects.txt) projects -> $out"
